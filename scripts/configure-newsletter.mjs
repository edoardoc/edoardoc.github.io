#!/usr/bin/env node
import fs from 'node:fs';

const root = new URL('../', import.meta.url);
const envFile = new URL('.env', root);
const values = {};
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*(NITROSEND_PUBLIC_KEY|NITROSEND_LIST_ID)\s*=\s*(.*?)\s*$/);
    if (match) values[match[1]] = match[2].replace(/^(['"])(.*)\1$/, '$2');
  }
}
const publicKey = process.env.NITROSEND_PUBLIC_KEY || values.NITROSEND_PUBLIC_KEY;
const listId = process.env.NITROSEND_LIST_ID || values.NITROSEND_LIST_ID;
if (!/^wpkey_live_[a-zA-Z0-9]+$/.test(publicKey || '')) {
  throw new Error('Set NITROSEND_PUBLIC_KEY to a public website key in .env.');
}
if (!/^[1-9]\d*$/.test(listId || '')) {
  throw new Error('Set NITROSEND_LIST_ID to the destination list ID in .env.');
}
const output = '// Generated by scripts/configure-newsletter.mjs. Public signup configuration only.\n'
  + 'window.NITROSEND_SIGNUP = Object.freeze(' + JSON.stringify({ publicKey, listId }, null, 2) + ');\n';
fs.writeFileSync(new URL('newsletter-config.js', root), output);
console.log('Updated public newsletter configuration. The .env file remains local.');
